import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('questions expand smoothly, reverse repeated clicks and retain keyboard and reduced-motion access', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const question = page.locator('.landing-questions details').nth(2)
  const summary = question.locator('summary')
  await summary.scrollIntoViewIfNeeded()
  await expect(question).toHaveCSS('opacity', '1')
  const height = () => question.evaluate((element) => element.getBoundingClientRect().height)
  const collapsed = await height()
  await summary.click()
  await expect.poll(height).toBeGreaterThan(collapsed)
  expect(await question.evaluate((element) => element.style.height)).not.toBe('')
  await expect.poll(() => question.evaluate((element) => element.style.height)).toBe('')
  await expect(question.getByRole('link', { name: 'API reference' })).toBeVisible()
  await summary.click()
  await summary.click()
  await expect.poll(() => question.evaluate((element) => element.style.height)).toBe('')
  await expect(question).toHaveAttribute('open', '')
  await summary.focus()
  await page.keyboard.press('Enter')
  await expect(question).not.toHaveAttribute('open')
  expect(await height()).toBe(collapsed)
  await page.keyboard.press('Space')
  await expect(question).toHaveAttribute('open', '')
  await expect(summary).toBeFocused()
  expect(await question.evaluate((element) => element.style.height)).toBe('')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 375, height: 812 })
  for (const item of await page.locator('.landing-questions details').all()) {
    const trigger = item.locator('summary')
    if (await item.getAttribute('open') !== null) await trigger.click()
    await trigger.click()
    await expect(item).toHaveAttribute('open', '')
    expect(await item.evaluate((element) => element.style.height)).toBe('')
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await summary.click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(question).not.toHaveAttribute('open')
  await expect.poll(() => question.evaluate((element) => element.style.height)).toBe('')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await summary.click()
  await page.getByRole('navigation', { name: 'Sections', exact: true }).getByRole('link', { name: 'Docs', exact: true }).click()
  await expect(page.locator('h1')).toHaveText('Make music with code')
  expect(errors).toEqual([])
})

test('Anime.js reveals lower sections once and responds to reduced motion without hiding content', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const landing = page.locator('.landing')
  const headline = page.locator('.landing-hero h1 span').first()
  await expect(landing).toHaveAttribute('data-hero-state', 'revealing')
  await expect.poll(() => headline.evaluate((element) => Number(getComputedStyle(element).opacity))).toBeGreaterThan(0)
  expect(await headline.evaluate((element) => Number(getComputedStyle(element).opacity))).toBeLessThan(1)
  await expect(landing).toHaveAttribute('data-hero-state', 'visible')
  const section = page.locator('.landing-paths-intro')
  await expect(section).toHaveAttribute('data-reveal-state', 'pending')
  await section.scrollIntoViewIfNeeded()
  await expect(section).toHaveAttribute('data-reveal-state', 'revealing')
  await expect(section).toHaveAttribute('data-reveal-state', 'visible')
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await section.scrollIntoViewIfNeeded()
  await expect(section).toHaveAttribute('data-reveal-state', 'visible')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(landing).toHaveAttribute('data-hero-state', 'static')
  expect(await page.locator('[data-reveal]').evaluateAll((groups) => groups.every((group) => group.getAttribute('data-reveal-state') === 'static'))).toBe(true)
  expect(await page.locator('[data-hero-reveal], [data-reveal-item]').evaluateAll((elements) => elements.every((element) => getComputedStyle(element).opacity === '1'))).toBe(true)
  // Cleanup while an entrance is running must leave the next route usable.
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('navigation', { name: 'Sections', exact: true }).getByRole('link', { name: 'Docs', exact: true }).click()
  await expect(page.locator('h1')).toHaveText('Make music with code')
  expect(errors).toEqual([])
})

test('the record moves only during explicit playback and stops for reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const player = page.getByRole('region', { name: 'Lo-fi session player' })
  const record = page.locator('.session-record')
  const transform = () => record.evaluate((element) => getComputedStyle(element).transform)
  const initial = await transform()
  await player.getByRole('button', { name: 'Play Lo-fi session' }).click()
  await expect(player.locator('.player-state')).toHaveText('Playing')
  await expect.poll(transform).not.toBe(initial)
  await player.getByRole('button', { name: 'Stop Lo-fi session' }).click()
  const stopped = await transform()
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  expect(await transform()).toBe(stopped)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await player.getByRole('button', { name: 'Play Lo-fi session' }).click()
  const reduced = await transform()
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  expect(await transform()).toBe(reduced)
  await player.getByRole('button', { name: 'Stop Lo-fi session' }).click()
})
